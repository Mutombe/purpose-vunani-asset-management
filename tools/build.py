"""Build the site's HTML pages from src/.

Each file in src/pages starts with a metadata comment:

    <!--meta {"title": "...", "description": "..."} -->

followed by the page body. The build wraps it in the shared <head>, adds the
footer and script, and expands these placeholders:

    {{nav}} {{strip}} {{cta}}       the partials in src/partials
    {{icon:name}}                   an inline Phosphor duotone icon (assets/icons/name.svg)
    {{icon:name:class}}             the same, with an extra class

The current page's nav link gets aria-current="page". Photo framing data
(tools/focus.py) is stamped onto every page afterwards.

    python tools/build.py
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # also works under python -P
import focus  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")

HEAD = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title}</title>
  <meta name="description" content="{description}">
  <meta name="theme-color" content="#062A2D">
  <link rel="icon" type="image/png" href="assets/brand/mark.png">
  <link rel="preload" href="assets/fonts/manrope-400.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="assets/fonts/jakarta-var.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="assets/fonts/montserrat-var.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="styles.css">
  <script>document.documentElement.classList.add('js')</script>
</head>
<body class="page-{page}">
<!-- Generated by tools/build.py from src/pages/{page}.html. Edit the source, not this file. -->
"""

TAIL = """
<script src="script.js"></script>
</body>
</html>
"""


def read(*parts):
    return open(os.path.join(SRC, *parts), encoding="utf-8").read()


_icons = {}


def icon(match):
    name, cls = match.group(1), match.group(2)
    if name not in _icons:
        svg = open(os.path.join(ROOT, "assets", "icons", f"{name}.svg"), encoding="utf-8").read().strip()
        _icons[name] = svg.replace("<svg ", '<svg class="ico" aria-hidden="true" focusable="false" ', 1)
    svg = _icons[name]
    if cls:
        svg = svg.replace('class="ico"', f'class="ico {cls}"', 1)
    return svg


def build_page(filename, partials):
    page = filename[:-5]
    src = read("pages", filename)
    meta_match = re.match(r"\s*<!--meta (\{.*?\}) -->\s*", src, re.S)
    meta = json.loads(meta_match.group(1))
    body = src[meta_match.end():]
    for name, html in partials.items():
        body = body.replace("{{" + name + "}}", html)
    footer = partials["footer"]
    html = HEAD.format(page=page, **meta) + body.rstrip() + "\n\n" + footer + TAIL
    html = re.sub(r"\{\{icon:([a-z0-9-]+)(?::([a-z0-9 _-]+))?\}\}", icon, html)
    html = html.replace(f'<a href="{page}.html">', f'<a href="{page}.html" aria-current="page">', 1)
    leftover = re.findall(r"\{\{[^}]*\}\}", html)
    if leftover:
        raise SystemExit(f"{filename}: unexpanded placeholders {leftover}")
    html = focus.stamp_html(html)
    out = os.path.join(ROOT, filename)
    open(out, "w", encoding="utf-8").write(html)
    return out


def main():
    partials = {name[:-5]: read("partials", name).rstrip() for name in os.listdir(os.path.join(SRC, "partials"))}
    for filename in sorted(os.listdir(os.path.join(SRC, "pages"))):
        if filename.endswith(".html"):
            print("built", os.path.relpath(build_page(filename, partials), ROOT))


if __name__ == "__main__":
    main()
